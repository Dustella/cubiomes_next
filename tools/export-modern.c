#include "../../cubiomes-viewer/cubiomes/biomenoise.c"

static void emit_spline(const Spline *s)
{
    if (s->len == 1) {
        printf("{\"value\":%.9g}", (double)((const FixSpline *)s)->val);
        return;
    }
    printf("{\"axis\":%d,\"locations\":[", s->typ);
    for (int i = 0; i < s->len; i++) printf("%s%.9g", i ? "," : "", (double)s->loc[i]);
    printf("],\"derivatives\":[");
    for (int i = 0; i < s->len; i++) printf("%s%.9g", i ? "," : "", (double)s->der[i]);
    printf("],\"values\":[");
    for (int i = 0; i < s->len; i++) { if (i) putchar(','); emit_spline(s->val[i]); }
    printf("]}");
}

static void emit_tree(const char *name, int order, const uint32_t *steps, int depth,
    const int32_t *params, int nparam, const uint64_t *nodes, int nnodes)
{
    printf("\"%s\":{\"order\":%d,\"steps\":[", name, order);
    for (int i = 0; i < depth; i++) printf("%s%u", i ? "," : "", steps[i]);
    printf("],\"params\":[");
    for (int i = 0; i < 2*nparam; i++) printf("%s%d", i ? "," : "", params[i]);
    printf("],\"nodes\":[");
    for (int i = 0; i < nnodes; i++) printf("%s\"%016" PRIx64 "\"", i ? "," : "", nodes[i]);
    printf("]}");
}

#define EMIT_TREE(n) emit_tree(#n, n##_order, n##_steps, sizeof(n##_steps)/sizeof(uint32_t), \
    &n##_param[0][0], sizeof(n##_param)/sizeof(n##_param[0]), n##_nodes, sizeof(n##_nodes)/sizeof(uint64_t))

int main(void)
{
    BiomeNoise bn;
    initBiomeNoise(&bn, MC_1_18);
    printf("{\"provenance\":\"MIT Cubiomes: biomenoise.c initBiomeNoise and tables/btree{18,192,19,20}.h; generated by tools/export-modern.c\",\"spline\":");
    emit_spline(bn.sp);
    printf(",\"trees\":{");
    EMIT_TREE(btree18); putchar(',');
    EMIT_TREE(btree192); putchar(',');
    EMIT_TREE(btree19); putchar(',');
    EMIT_TREE(btree20);
    printf("}}\n");
    return ferror(stdout) ? 1 : 0;
}
