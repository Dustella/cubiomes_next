// Rebuild the checked-in clean-room data from local MIT Cubiomes only.
// Run: bun tools/export-modern.ts [C compiler executable]
import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';

const root = resolve(import.meta.dir, '..');
const source = '../cubiomes-viewer/cubiomes';
const temp = await mkdtemp(join(tmpdir(), 'cubiomes-modern-'));
try {
  const exe = join(temp, process.platform === 'win32' ? 'export-modern.exe' : 'export-modern');
  const compile = Bun.spawnSync([process.argv[2] ?? 'gcc', '-O2', '-std=c99',
    'tools/export-modern.c', `${source}/noise.c`, `${source}/layers.c`, `${source}/biomes.c`, '-lm', '-o', exe.replaceAll('\\', '/')],
    { cwd: root });
  if (compile.exitCode !== 0) throw new Error(new TextDecoder().decode(compile.stderr));
  const generated = Bun.spawnSync([exe]);
  if (generated.exitCode !== 0) throw new Error(new TextDecoder().decode(generated.stderr));
  const json = JSON.parse(new TextDecoder().decode(generated.stdout));
  await Bun.write(resolve(root, 'src/modern/data.ts'),
    '// Generated by tools/export-modern.ts from MIT Cubiomes; do not edit by hand.\n' +
    '// Copyright (c) 2020-2024 Cubitect. Attribution and license: cubiomes-viewer/cubiomes/LICENSE.\n' +
    'export default ' + JSON.stringify(json) + ';\n');
} finally {
  await rm(temp, { recursive: true, force: true });
}
